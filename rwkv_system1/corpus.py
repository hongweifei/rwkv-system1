def generate(
    spec: TaskSpec,
    n: int,
    seed: int,
    n_cues: int = 2,
    p_neutral: float = 0.35,
    n_filler: int = 3,
) -> list[DecisionExample]:
    rng = random.Random(seed)
    k = len(spec.options)
    prior = [1.0 / k] * k
    out: list[DecisionExample] = []
    for _ in range(n):
        cues = _pick_cues(rng, spec, rng.randrange(k), n_cues, p_neutral)
        probs = _posterior(prior, cues)
        answer = rng.choices(range(k), weights=probs, k=1)[0]
        out.append(
            DecisionExample(
                state=_render(rng, spec, cues, n_filler),
                question=Question(
                    spec.name,
                    spec.question_name,
                    spec.type,
                    render_options(spec.type, spec.options),
                    spec.options,
                ),
                answer=answer,
                true_probs=probs,
                meta={"cues": [c.word for c in cues], "spec": spec.name},
            )
        )
    return out


def split(
    spec: TaskSpec,
    n_train: int,
    n_dev: int,
    n_test: int,
    seed: int = 0,
    **kwargs,
) -> tuple[list[DecisionExample], list[DecisionExample], list[DecisionExample]]:
    """Disjoint splits. The cue vocabulary is shared, only the draws differ."""
    train = generate(spec, n_train, seed=seed, **kwargs)
    dev = generate(spec, n_dev, seed=seed + 1_000_003, **kwargs)
    test = generate(spec, n_test, seed=seed + 2_000_003, **kwargs)
    return train, dev, test



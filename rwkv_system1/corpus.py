"""Synthetic decision corpora with *analytic* posteriors.

Off-the-shelf classification sets only give you a hard label, so you can measure
accuracy but not calibration -- any ECE you compute is against a proxy.  Here each
example carries the true posterior ``P(answer | context)`` in closed form: a context
is generated by drawing cue words, each cue carries a likelihood over the classes,
and the posterior is the normalised product of the cues' likelihoods.  The label is
then sampled from that posterior.

That buys three things:

* an honest calibration target, so RLCD can be *measured*, not asserted;
* controllable difficulty -- a single shared cue leaves the posterior near-uniform,
  which is where an uncalibrated model will wrongly say 0.99;
* no download, no licence question, fully reproducible from a seed.
"""

from __future__ import annotations

import random
from dataclasses import dataclass

import torch

from .decision import DecisionExample, DecisionType, Question, render_options


@dataclass(frozen=True)
class Cue:
    word: str
    #: likelihood of each class emitting this cue; need not be normalised
    likelihood: tuple[float, ...]


@dataclass(frozen=True)
class TaskSpec:
    name: str
    question_name: str
    type: DecisionType
    options: list[str]
    cues: dict[str, list[Cue]]
    neutral_cues: list[Cue]
    frames: list[str]


def _softmax(logits: list[float]) -> list[float]:
    m = max(logits)
    exps = [torch.exp(torch.tensor(v - m, dtype=torch.float64)).item() for v in logits]
    total = sum(exps)
    return [e / total for e in exps]


def _posterior(prior: list[float], cues: list[Cue]) -> list[float]:
    logits = [float(torch.log(torch.tensor(p, dtype=torch.float64))) for p in prior]
    for cue in cues:
        for c in range(len(logits)):
            logits[c] += float(torch.log(torch.tensor(max(cue.likelihood[c], 1e-12))))
    return _softmax(logits)


def _pick_cues(
    rng: random.Random, spec: TaskSpec, answer: int, n_cues: int, p_neutral: float
) -> list[Cue]:
    pool = list(spec.cues[spec.options[answer]])
    rng.shuffle(pool)
    chosen: list[Cue] = []
    for i in range(n_cues):
        if rng.random() < p_neutral:
            chosen.append(rng.choice(spec.neutral_cues))
        elif i < len(pool):
            chosen.append(pool[i])
        else:
            chosen.append(rng.choice(spec.neutral_cues))
    return chosen


FILLER = [
    "客户通过在线客服提交了工单。",
    "该工单来自移动端 App。",
    "用户已注册超过一年，是付费会员。",
    "工单由机器人初步受理后转人工。",
    "用户希望尽快得到答复。",
    "此前未有过相关记录。",
    "该用户所在地区为华东。",
]


def _render(rng: random.Random, spec: TaskSpec, cues: list[Cue], n_filler: int) -> str:
    frame = rng.choice(spec.frames)
    body = frame.format(cues="、".join(c.word for c in cues))
    tail = "".join(rng.sample(FILLER, min(n_filler, len(FILLER))))
    return body + tail


